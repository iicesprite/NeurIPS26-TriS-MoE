std::vector<torch::Tensor> build_grouped_route(
    torch::Tensor selected_experts,
    int64_t num_experts,
    int64_t m_tile) {
  TORCH_CHECK(selected_experts.is_cuda(), "selected_experts must be a CUDA tensor");
  TORCH_CHECK(selected_experts.dim() == 2, "selected_experts must be 2D [tokens, top_k]");
  TORCH_CHECK(num_experts >= 0, "num_experts must be non-negative");
  TORCH_CHECK(m_tile > 0, "m_tile must be positive");

  const at::cuda::OptionalCUDAGuard device_guard(device_of(selected_experts));
  const auto device = selected_experts.device();
  const auto num_tokens = selected_experts.size(0);
  const auto top_k = selected_experts.size(1);
  auto long_opts = torch::TensorOptions().device(device).dtype(torch::kLong);
  auto int_opts = torch::TensorOptions().device(device).dtype(torch::kInt32);

  auto flat_selected_experts = selected_experts.contiguous().reshape({-1}).to(torch::kLong);
  auto sort_result = torch::sort(flat_selected_experts, 0, false);
  auto grouped_experts = std::get<0>(sort_result).contiguous();
  auto perm = std::get<1>(sort_result).contiguous();

  auto token_template = torch::arange(num_tokens, long_opts)
      .unsqueeze(1)
      .expand({num_tokens, top_k})
      .reshape({-1});
  auto slot_template = torch::arange(top_k, long_opts)
      .unsqueeze(0)
      .expand({num_tokens, top_k})
      .reshape({-1});
  auto grouped_token_indices = token_template.index_select(0, perm).contiguous();
  auto grouped_slots = slot_template.index_select(0, perm).contiguous();

  auto expert_counts = torch::bincount(grouped_experts, {}, num_experts);
  auto active_expert_ids_long = torch::nonzero(expert_counts > 0).flatten().contiguous();
  auto segment_lengths = expert_counts.index_select(0, active_expert_ids_long);
  auto zero_long = torch::zeros({1}, long_opts);
  auto segment_offsets = torch::cat({zero_long, torch::cumsum(segment_lengths, 0)}, 0).to(torch::kInt32).contiguous();
  auto problem_lengths = torch::div(segment_lengths + (m_tile - 1), m_tile, "floor");
  auto problem_offsets_long = torch::cat({zero_long, torch::cumsum(problem_lengths, 0)}, 0);
  auto problem_offsets = problem_offsets_long.to(torch::kInt32).contiguous();
  auto total_problem_tiles = problem_offsets_long.slice(0, problem_offsets_long.size(0) - 1, problem_offsets_long.size(0)).to(torch::kCPU, torch::kLong).contiguous();
  auto expert_ids = active_expert_ids_long.to(torch::kInt32).contiguous();

  return {
      perm,
      grouped_token_indices,
      grouped_slots,
      expert_ids,
      segment_offsets,
      problem_offsets,
      total_problem_tiles,
  };
}

